require('dotenv').config({ path: require('path').join(__dirname, '../../..', '.env') });
const fs = require('fs');
const path = require('path');
const axios = require('axios');

const INPUT_FILE = path.join(__dirname, 'data', 'forestry-england-forests.json');
const OUTPUT_FILE = path.join(__dirname, 'data', 'forestry-england-enriched.json');

const GEMINI_API_KEY = process.env.GEMINI_API_KEY;
const GEMINI_URL = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash-lite:generateContent?key=${GEMINI_API_KEY}`;

const sleep = ms => new Promise(r => setTimeout(r, ms));

// Derive a rough region name from lat/lng for context
function roughRegion(lat, lng) {
    if (lat > 54.5) return 'North England';
    if (lat > 53.5) return 'Northern England';
    if (lat > 52.5) return 'Midlands';
    if (lng < -3.5) return 'South West England';
    return 'South East England';
}

async function generateDescription(forest) {
    const region = roughRegion(forest.lat, forest.lng);
    const prompt = `Write a 2-3 sentence description of ${forest.name}, a Forestry England woodland in ${region}. Focus on the natural environment, wildlife, and what people can experience there (walking, cycling, nature). Do not mention specific facilities or opening times. Keep it engaging and factual. Do not start with the forest name.`;

    const response = await axios.post(GEMINI_URL, {
        contents: [{ parts: [{ text: prompt }] }],
        generationConfig: { temperature: 0.7, maxOutputTokens: 1024 }
    }, { timeout: 15000 });

    return response.data.candidates[0].content.parts[0].text.trim();
}

async function main() {
    console.log('🌲 Forestry England — Gemini Description Enrichment\n');

    const forests = JSON.parse(fs.readFileSync(INPUT_FILE, 'utf8'));
    console.log(`📂 Loaded ${forests.length} forests\n`);

    // Load existing output to resume if interrupted
    let enriched = [];
    if (fs.existsSync(OUTPUT_FILE)) {
        enriched = JSON.parse(fs.readFileSync(OUTPUT_FILE, 'utf8'));
        console.log(`▶️  Resuming — ${enriched.length} already done\n`);
    }

    const done = new Set(enriched.map(f => f.entityId));
    const todo = forests.filter(f => !done.has(f.entityId));
    console.log(`🚀 Generating descriptions for ${todo.length} forests...\n`);

    for (const forest of todo) {
        try {
            const description = await generateDescription(forest);
            enriched.push({
                ...forest,
                description,
                'Suggestion-Tags': ['Forestry England Import'],
                'AI-Notes': `[Forestry England Import]: Location data extracted from forestryengland.uk map. Description AI-generated by Gemini.`
            });
            fs.writeFileSync(OUTPUT_FILE, JSON.stringify(enriched, null, 2));
            console.log(`   ✅ ${forest.name}`);
        } catch (err) {
            console.error(`   ❌ ${forest.name} — ${err.message}`);
            enriched.push({ ...forest, description: null, 'Suggestion-Tags': ['Forestry England Import'], 'AI-Notes': `[Forestry England Import]: Location data extracted from forestryengland.uk map. Description AI-generated by Gemini.` });
            fs.writeFileSync(OUTPUT_FILE, JSON.stringify(enriched, null, 2));
        }
        await sleep(200); // stay within rate limits
    }

    const withDesc = enriched.filter(f => f.description).length;
    console.log(`\n🎉 Done! ${withDesc}/${enriched.length} forests have descriptions.`);
}

main();
